"""Conformance test (PRO-09): every message fixture validates in Python exactly as in TypeScript.

The reference partition is ``shared/fixtures/messages/expected.json`` (generated by PRO-06's
``npm run generate -w shared``); valid fixtures must pass, invalid ones must fail with an issue at
the expected ``instancePath``.
"""

from __future__ import annotations

from typing import Any

import pytest
from jsonschema import Draft202012Validator

from remoteview_protocol import (
    LENIENT_ENUM_DEFINITIONS,
    PROTOCOL_VERSION,
    Issue,
    compile_schemas,
    load_schemas,
    message_types,
    validate_message,
)

from .conftest import FIXTURES_DIR, PROTOCOL_DOC, SCHEMA_DIR, read_json

STRICT = compile_schemas()
LENIENT = compile_schemas(tolerate_unknown_enums=True)


def _fixture_cases() -> list[tuple[str, str, bool, str | None]]:
    expected = read_json(FIXTURES_DIR / "messages" / "expected.json")
    return [(e["file"], e["type"], e["valid"], e.get("instancePath")) for e in expected["fixtures"]]


def _example(type_: str) -> dict[str, Any]:
    return read_json(FIXTURES_DIR / "messages" / type_ / "valid-example.json")


@pytest.mark.parametrize(("file", "type_", "valid", "instance_path"), _fixture_cases())
def test_fixture_partition_matches_typescript(
    file: str, type_: str, valid: bool, instance_path: str | None
) -> None:
    raw = read_json(FIXTURES_DIR / "messages" / file)
    message = raw if valid else raw["message"]
    issues = validate_message(message, type_, STRICT)
    if valid:
        assert issues == [], f"{file}: {issues}"
    else:
        assert issues, f"{file} should be invalid"
        assert instance_path in {i.instance_path for i in issues}, f"{file}: {issues}"


def test_expected_json_covers_every_fixture_file(expected: dict[str, Any]) -> None:
    on_disk = sorted(
        f"{d.name}/{f.name}"
        for d in (FIXTURES_DIR / "messages").iterdir()
        if d.is_dir()
        for f in d.iterdir()
        if f.suffix == ".json"
    )
    assert [e["file"] for e in expected["fixtures"]] == on_disk
    assert len(on_disk) > 300


def test_packaged_schemas_equal_shared_schema_directory() -> None:
    """Criterion 3: the package carries its own copy of ``shared/schema`` (generated, checked)."""
    packaged = load_schemas()
    files = sorted(p.name for p in SCHEMA_DIR.glob("*.schema.json"))
    assert sorted(packaged) == files
    for name in files:
        assert packaged[name] == read_json(SCHEMA_DIR / name), name
        Draft202012Validator.check_schema(packaged[name])


def test_message_types_match_schema_files_and_fixture_directories() -> None:
    types = message_types()
    dirs = sorted(d.name for d in (FIXTURES_DIR / "messages").iterdir() if d.is_dir())
    assert types == dirs
    assert len(types) == 28
    assert set(STRICT.by_type) == set(types)


def test_unknown_type_and_non_object_are_reported_at_root_or_type() -> None:
    assert validate_message([], "ping", STRICT) == [Issue("", "type", "must be object")]
    assert validate_message({"protocolVersion": "1.0", "type": "scene.camera"}, None, STRICT) == [
        Issue("/type", "type", "unknown message type for protocol 1.x (§2)")
    ]


def test_issues_never_contain_the_offending_value() -> None:
    joined = {**_example("viewer.joined"), "viewerToken": "SECRET-not-base64url!"}
    issues = validate_message(joined, None, STRICT)
    assert {i.instance_path for i in issues} == {"/viewerToken"}
    assert "SECRET" not in repr(issues)
    bad_code = {**_example("viewer.join"), "code": "7KQ0X"}
    assert "7KQ0X" not in repr(validate_message(bad_code, None, STRICT))


def test_tolerate_unknown_enums_opens_error_codes_and_reasons_only() -> None:
    defs = load_schemas()["defs.schema.json"]["definitions"]
    reasons = [n for n in defs if n.endswith("Reason")]
    assert len(reasons) >= 5
    assert sorted(LENIENT_ENUM_DEFINITIONS) == sorted(["errorCode", *reasons])
    future_error = {**_example("error"), "code": "FUTURE_CODE_1_1"}
    assert validate_message(future_error, None, STRICT)
    assert validate_message(future_error, None, LENIENT) == []
    future_reason = {**_example("session.expired"), "reason": "RELAY_MAINTENANCE"}
    assert validate_message(future_reason, None, STRICT)
    assert validate_message(future_reason, None, LENIENT) == []
    assert validate_message({**future_error, "code": ""}, None, LENIENT)
    assert validate_message({**future_error, "code": 7}, None, LENIENT)
    begin = {**_example("scene.snapshot.begin"), "format": "gltf"}
    assert validate_message(begin, None, LENIENT)
    assert LENIENT.tolerate_unknown_enums and not STRICT.tolerate_unknown_enums


def test_unknown_fields_and_higher_minor_versions_are_accepted() -> None:
    ping = _example("ping")
    assert validate_message({**ping, "futureField": 1}, None, STRICT) == []
    assert validate_message({**ping, "protocolVersion": "1.7"}, None, STRICT) == []
    assert validate_message({**ping, "protocolVersion": "2.0"}, None, STRICT)


def test_protocol_version_matches_the_document() -> None:
    doc = PROTOCOL_DOC.read_text(encoding="utf-8")
    assert f"Protocol version `{PROTOCOL_VERSION}`" in doc
