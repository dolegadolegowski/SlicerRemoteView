#!/usr/bin/env node
/**
 * C# code generation for `shared/` (PRO-17): `npm run generate:cs -w shared`, also run by `npm run generate -w shared`.
 *
 * Writes **only** `shared/cs/RemoteView.Protocol/` (ADR 0007 errata: the copy into `quest-app/Assets/RemoteView/
 * Protocol/Generated/`, with `.asmdef` and `link.xml`, is QST-03's job):
 *
 * - `Messages.cs` — one `public partial class` per message type of docs/protocol.md §11 (28), the nested shapes of
 *   `defs` (`ClientInfo`, `NodeChange`, `Limits`, ...) and one `enum` per schema enum; Newtonsoft.Json attributes only
 *   (`[JsonProperty("camelCase")]`, `[JsonConverter]` on the enums), plain auto-properties, no `record`, no `init`
 *   (Unity LTS has no `IsExternalInit`, `prompts/01-protocol.md`). Generated by quicktype-core 26.0.0 (the PRO-02
 *   spike choice; NJsonSchema has no `$defs`/`const`, see shared/README.md) from the same bundle PRO-11 feeds to the TS
 *   and Python generators, after the adjustments below.
 * - `MessageTypes.cs` — the `type` string of every class and a type → class registry for the dispatcher (QST-03).
 *
 * Adjustments to the schemas before quicktype sees them (the files in `schema/` are untouched):
 *
 * - validation keywords (`pattern`, `minLength`, `maximum`, `minItems`, ...) are dropped: the relay validates, and
 *   quicktype would turn them into `MinMaxLengthCheckConverter` classes with unstable names (`PurpleMinMax...`);
 * - `oneOf`/`anyOf`/`not`/`if`/`then` on objects only list required/forbidden property sets in these schemas
 *   (shared/README.md "Schema conventions"; every property is declared in `properties`), so they are dropped too;
 * - the `const` of every `type` property is dropped (quicktype would emit 28 single-value enums); instead each class
 *   gets `public string Type { get; set; } = "<type>";` below;
 * - `defs.platform` is not referenced by a message (the wire field stays a lenient string, §14), so it is added as an
 *   extra root to get the `Platform` enum.
 *
 * Adjustments to quicktype's output (all anchored; the script exits 1 with a message when an anchor does not match, so a quicktype
 * upgrade cannot silently change the result):
 *
 * - every enum gets an `Other` member (unless it has one) and its converter returns it for an unknown wire value
 *   instead of throwing (§14 "tolerate unknown enum values", PRO-02 review); writing `Other` throws, it is receive-only;
 * - every enum carries `[JsonConverter(typeof(<Enum>Converter))]`, so a plain `JsonConvert.DeserializeObject<T>(json)`
 *   works without quicktype's `Converter.Settings` (internal);
 * - each class initialises `Type` to its message type.
 *
 * Usage: `node scripts/generate-cs.mjs [--check] [--out-dir <dir>]` (write mode prunes stale `*.cs` files that carry the
 * GENERATED banner and only warns about others). `--check` exits 1 when a file in the output
 * directory differs from a fresh generation, is missing, or is an unexpected extra `.cs` file (ADR 0007 §4 drift check).
 */
import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { InputData, JSONSchemaInput, JSONSchemaStore, quicktype } from "quicktype-core";
import { bundleSchemas } from "./lib/bundle.mjs";

const shared = resolve(dirname(fileURLToPath(import.meta.url)), "..");
export const CS_OUT_DIR = resolve(shared, "cs/RemoteView.Protocol");
const SCHEMA_DIR = resolve(shared, "schema");
const NAMESPACE = "RemoteView.Protocol";
const BUNDLE_URI = "https://slicerremoteview.dev/schema/bundle.json";

const GENERATED_BY =
  "GENERATED by shared/scripts/generate-cs.mjs from shared/schema/*.schema.json — do not edit.\n" +
  "Regenerate with `npm run generate -w shared`; CI fails on drift (ADR 0007 §4).";

const VALIDATION_KEYWORDS = new Set([
  ...["pattern", "minLength", "maxLength", "minimum", "maximum", "exclusiveMinimum", "format"],
  ...["exclusiveMaximum", "minItems", "maxItems", "uniqueItems", "const"],
]);
const OBJECT_CONSTRAINTS = ["oneOf", "anyOf", "not", "if", "then", "else"];

/** Copy of `node` without validation keywords and without the combinators that only constrain property sets. */
function forCsharp(node) {
  if (Array.isArray(node)) return node.map(forCsharp);
  if (node === null || typeof node !== "object") return node;
  const isObjectSchema = node.properties !== undefined;
  const out = {};
  for (const [key, value] of Object.entries(node)) {
    if (VALIDATION_KEYWORDS.has(key)) continue;
    if (isObjectSchema && OBJECT_CONSTRAINTS.includes(key)) continue;
    // `properties`/`definitions` are maps of schemas: recurse into the values, not into the key names.
    if ((key === "properties" || key === "definitions") && value && typeof value === "object") {
      out[key] = Object.fromEntries(Object.entries(value).map(([k, v]) => [k, forCsharp(v)]));
    } else out[key] = forCsharp(value);
  }
  return out;
}

class BundleStore extends JSONSchemaStore {
  constructor(bundle) {
    super();
    this.bundle = bundle;
  }
  async fetch(address) {
    return address === BUNDLE_URI ? this.bundle : undefined;
  }
}

function fail(message) {
  throw new Error(`generate-cs: ${message}`);
}

/** Replaces `pattern` in `text`, requiring exactly `expected` matches (`"some"`: at least one). */
function replaceExactly(text, pattern, replacement, expected, label) {
  let count = 0;
  const result = text.replace(pattern, (...args) => {
    count += 1;
    return typeof replacement === "function" ? replacement(...args) : replacement;
  });
  if (expected === "some" ? count === 0 : count !== expected)
    fail(`${label}: expected ${expected} match(es) in quicktype output, found ${count}`);
  return result;
}

async function runQuicktype(bundle, messageNames) {
  const schemaInput = new JSONSchemaInput(new BundleStore(forCsharp(bundle)));
  const roots = [...messageNames, "Platform"];
  for (const name of roots) {
    const pointer = name === "Platform" ? "platform" : name;
    await schemaInput.addSource({
      name,
      schema: JSON.stringify({ $ref: `${BUNDLE_URI}#/definitions/${pointer}` }),
    });
  }
  const inputData = new InputData();
  inputData.addInput(schemaInput);
  const { lines } = await quicktype({
    inputData,
    lang: "csharp",
    rendererOptions: {
      namespace: NAMESPACE,
      framework: "NewtonSoft",
      features: "complete",
      "csharp-version": "6",
    },
  });
  return lines.join("\n");
}

/** Applies the anchored adjustments described in the file header to quicktype's C#. */
function adjust(source, typeByName) {
  let text = source.replace(/[ \t]+$/gm, "");

  // quicktype names the enum of a non-object root `<Root>Enum` and adds a `<Root>` holder class with `FromJson`;
  // the viewer-platform enum should simply be `Platform`.
  text = replaceExactly(
    text,
    /^ {4}public class Platform\n {4}\{\n(?: {8}.*\n)*? {4}\}\n\n/gm,
    "",
    1,
    "Platform holder class",
  );
  text = replaceExactly(text, /PlatformEnum/g, "Platform", "some", "PlatformEnum rename");

  // Enums: `Other` member, `[JsonConverter]` attribute, tolerant converter.
  const enums = [];
  text = replaceExactly(
    text,
    /^( {4})public enum (\w+) \{ ([^}]*) \};$/gm,
    (_match, indent, name, members) => {
      enums.push(name);
      const list = members.split(",").map((m) => m.trim());
      const withOther = list.includes("Other") ? list : [...list, "Other"];
      return `${indent}[JsonConverter(typeof(${name}Converter))]\n${indent}public enum ${name} { ${withOther.join(", ")} };`;
    },
    "some",
    "enum declarations",
  );
  if (text.split("\n").some((line) => /^\s*public enum /.test(line) && !line.includes(" };")))
    fail("an enum declaration is not on one line any more");
  if (enums.length === 0) fail("no enum found in quicktype output");
  for (const name of enums) {
    text = replaceExactly(
      text,
      new RegExp(`throw new Exception\\("Cannot unmarshal type ${name}"\\);`),
      `return ${name}.Other; // unknown wire value: docs/protocol.md §14`,
      1,
      `${name} converter fallback`,
    );
    // Make the converter reachable from the attribute in any assembly layout (Unity asmdef).
    text = replaceExactly(
      text,
      new RegExp(`internal class ${name}Converter : JsonConverter`),
      `public class ${name}Converter : JsonConverter`,
      1,
      `${name} converter visibility`,
    );
  }
  if (/Cannot unmarshal type/.test(text)) fail("a non-enum converter still throws on unmarshal");

  // Classes: `Type` defaults to the message type.
  for (const [className, messageType] of Object.entries(typeByName)) {
    const classStart = text.indexOf(`public partial class ${className}\n`);
    if (classStart < 0) fail(`class ${className} not found`);
    const classEnd = text.indexOf("\n    }\n", classStart);
    if (classEnd < 0) fail(`end of class ${className} not found`);
    const body = text.slice(classStart, classEnd);
    const typeProperty = '        [JsonProperty("type")]\n        public string Type { get; set; }';
    if (!body.includes(typeProperty)) fail(`${className}.Type is not a plain string property`);
    text =
      text.slice(0, classStart) +
      body.replace(typeProperty, `${typeProperty} = ${JSON.stringify(messageType)};`) +
      text.slice(classEnd);
  }

  // quicktype prints its own banner above the namespace; ours replaces it.
  const namespaceAt = text.indexOf(`namespace ${NAMESPACE}`);
  if (namespaceAt < 0) fail("namespace not found");
  const banner = GENERATED_BY.split("\n")
    .map((l) => `// ${l}`)
    .join("\n");
  return `// <auto-generated />\n${banner}\n\n${text.slice(namespaceAt).trimEnd()}\n`;
}

function messageTypesSource(messageNames, typeByName) {
  const consts = messageNames.map(
    (name) =>
      `        /// <summary>\`type\` of <see cref="${NAMESPACE}.${name}"/>.</summary>\n` +
      `        public const string ${name} = ${JSON.stringify(typeByName[name])};`,
  );
  const entries = messageNames.map(
    (name) => `            { ${name}, typeof(${NAMESPACE}.${name}) },`,
  );
  return [
    "// <auto-generated />",
    ...GENERATED_BY.split("\n").map((l) => `// ${l}`),
    "",
    "namespace RemoteView.Protocol",
    "{",
    "    using System;",
    "    using System.Collections.Generic;",
    "",
    "    /// <summary>",
    "    /// The `type` string of every protocol message (docs/protocol.md §11) and the class that carries it.",
    "    /// Constants are named after the classes; `ErrorMessage` is the `error` message.",
    "    /// </summary>",
    "    public static class MessageTypes",
    "    {",
    consts.join("\n\n"),
    "",
    "        /// <summary>",
    "        /// Message `type` string to its class, for the receive-side dispatcher. Pick the class from the `type` peeked in the",
    "        /// received JSON and check that the instance's `Type` still equals the key: `Type` is a settable property.",
    "        /// </summary>",
    "        public static readonly IReadOnlyDictionary<string, Type> Classes = new Dictionary<string, Type>",
    "        {",
    entries.join("\n"),
    "        };",
    "    }",
    "}",
    "",
  ].join("\n");
}

/** Fresh generation: file name → content. Pure (reads `schema/` only). */
export async function renderCs(schemaDir = SCHEMA_DIR) {
  const { bundle, messageNames, typeByName } = bundleSchemas(schemaDir);
  const messages = adjust(await runQuicktype(bundle, messageNames), typeByName);
  return new Map([
    ["Messages.cs", messages],
    ["MessageTypes.cs", messageTypesSource(messageNames, typeByName)],
  ]);
}

/**
 * Writes the generation into `outDir`, or with `check` only compares.
 * @returns {Promise<string[]>} drift descriptions (empty = in sync); in write mode always empty
 */
export async function syncCs({ check = false, outDir = CS_OUT_DIR, schemaDir = SCHEMA_DIR } = {}) {
  const files = await renderCs(schemaDir);
  const drift = [];
  for (const [name, content] of files) {
    const path = resolve(outDir, name);
    const current = existsSync(path) ? readFileSync(path, "utf8") : null;
    if (current === content) continue;
    if (check) {
      drift.push(`${path} is ${current === null ? "missing" : "out of date"}`);
      continue;
    }
    mkdirSync(outDir, { recursive: true });
    writeFileSync(path, content);
    console.log(`wrote ${path}`);
  }
  for (const stale of existsSync(outDir) ? readdirSync(outDir) : []) {
    if (!stale.endsWith(".cs") || files.has(stale)) continue;
    const path = resolve(outDir, stale);
    // Only files that carry our banner are ours to delete; anything else is reported and left alone.
    const generated = readFileSync(path, "utf8").startsWith(
      "// <auto-generated />\n// GENERATED by shared/scripts/generate-cs.mjs",
    );
    if (check) drift.push(`${path} is not generated — delete it`);
    else if (generated) {
      rmSync(path);
      console.log(`removed ${path}`);
    } else console.warn(`kept ${path}: not generated by this script — delete it by hand`);
  }
  return drift;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const args = process.argv.slice(2);
  const outIndex = args.indexOf("--out-dir");
  const outValue = outIndex >= 0 ? args[outIndex + 1] : undefined;
  const unknown = args.filter(
    (a, i) => a !== "--check" && a !== "--out-dir" && !(outIndex >= 0 && i === outIndex + 1),
  );
  if ((outIndex >= 0 && (!outValue || outValue.startsWith("--"))) || unknown.length > 0) {
    console.error("usage: generate-cs.mjs [--check] [--out-dir <dir>]");
    process.exit(2);
  }
  try {
    const drift = await syncCs({
      check: args.includes("--check"),
      outDir: outValue ? resolve(outValue) : CS_OUT_DIR,
    });
    for (const line of drift)
      console.error(`drift: ${line} — run \`npm run generate -w shared\` (C# types)`);
    if (drift.length > 0) process.exit(1);
  } catch (error) {
    console.error(error instanceof Error ? error.message : error);
    process.exit(1);
  }
}
