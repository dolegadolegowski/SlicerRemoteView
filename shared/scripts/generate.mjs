#!/usr/bin/env node
/**
 * Generation entry point for `shared/` (`npm run generate -w shared`, ADR 0007 §2).
 *
 * Writes committed artefacts from the schemas and fixtures. Drift check: `--check` (npm script
 * `generate:check`) exits 1 when any output is stale; `test/lib.test.ts` runs it, and `npm run check`
 * (PRO-12) / the CI workflow (DEP-01) call `npm run generate:check -w shared` the same way:
 *
 * 1. `ts/generated/schemas.ts` — every `schema/*.schema.json` embedded as a TypeScript module, so
 *    `compileSchemas()` works in browsers and in consumers' bundles without `node:fs` (PRO-06).
 * 2. `fixtures/messages/expected.json` — the valid/invalid partition of every message fixture with
 *    the expected `instancePath`, the reference the Python (PRO-09) and C# conformance tests
 *    compare against so all languages agree with the TypeScript run.
 *
 * 3. `py/remoteview_protocol/schema/*.schema.json` — a byte-identical copy of `schema/`, so the Python
 *    package carries its schemas as package data and the vendored copy in the Slicer extension works
 *    without the repository (PRO-09, ADR 0007 §3).
 *
 * 4. `ts/generated/messages.ts` — one interface per message type + the `AnyMessage` union, from the bundled schemas
 *    (`scripts/lib/bundle.mjs`) via `json-schema-to-typescript` (PRO-11).
 * 5. `py/remoteview_protocol/generated.py` — `TypedDict`s and `AnyMessage` from the same bundle via
 *    `datamodel-code-generator` (PRO-11). Needs the local venv of `shared/README.md`; `--skip-python` skips this step
 *    (the vitest drift test uses it, so `npm test` works without Python; `npm run check` does not skip).
 */
import { execFileSync } from "node:child_process";
import {
  existsSync,
  mkdirSync,
  mkdtempSync,
  readdirSync,
  readFileSync,
  rmSync,
  writeFileSync,
} from "node:fs";
import { tmpdir } from "node:os";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { compile } from "json-schema-to-typescript";
import { bundleSchemas } from "./lib/bundle.mjs";

const shared = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const schemaDir = resolve(shared, "schema");
const fixturesDir = resolve(shared, "fixtures/messages");
const check = process.argv.includes("--check");
const skipPython = process.argv.includes("--skip-python");

const readJson = (path) => JSON.parse(readFileSync(path, "utf8"));
let drift = false;

/** Writes `content` unless `--check`, in which case a differing file is reported and sets exit code 1. */
function emit(path, content) {
  let current;
  try {
    current = readFileSync(path, "utf8");
  } catch {
    current = null;
  }
  if (current === content) return;
  if (check) {
    drift = true;
    console.error(`drift: ${path} is out of date — run \`npm run generate -w shared\``);
    return;
  }
  mkdirSync(dirname(path), { recursive: true });
  writeFileSync(path, content);
  console.log(`wrote ${path}`);
}

// 1. ts/generated/schemas.ts
const schemaFiles = readdirSync(schemaDir)
  .filter((f) => f.endsWith(".schema.json"))
  .sort();
const entries = schemaFiles.map((file) => {
  const schema = readJson(resolve(schemaDir, file));
  return `  ${JSON.stringify(file)}: ${JSON.stringify(schema, null, 2).replace(/\n/g, "\n  ")},`;
});
emit(
  resolve(shared, "ts/generated/schemas.ts"),
  [
    "// GENERATED by shared/scripts/generate.mjs from shared/schema/*.schema.json — do not edit.",
    "// Regenerate with `npm run generate -w shared`; CI fails on drift (ADR 0007 §2).",
    "",
    "/** Every protocol schema (docs/protocol.md v1.0) keyed by its file name in `shared/schema/`. */",
    "export const SCHEMA_FILES: Readonly<Record<string, Record<string, unknown>>> = {",
    ...entries,
    "};",
    "",
  ].join("\n"),
);

// 2. fixtures/messages/expected.json
const fixtures = [];
for (const type of readdirSync(fixturesDir, { withFileTypes: true })
  .filter((d) => d.isDirectory())
  .map((d) => d.name)
  .sort()) {
  for (const file of readdirSync(resolve(fixturesDir, type))
    .filter((f) => f.endsWith(".json"))
    .sort()) {
    const path = `${type}/${file}`;
    if (file.startsWith("valid-")) fixtures.push({ file: path, type, valid: true });
    else if (file.startsWith("invalid-")) {
      const { expect } = readJson(resolve(fixturesDir, type, file));
      fixtures.push({ file: path, type, valid: false, instancePath: expect.instancePath });
    }
  }
}
emit(
  resolve(fixturesDir, "expected.json"),
  JSON.stringify(
    {
      $comment:
        "GENERATED by shared/scripts/generate.mjs — the valid/invalid partition every language's conformance test must reproduce (docs/plan/protocol.md PRO-06, PRO-09). `type` names the schema to validate against (the fixture directory), `instancePath` the JSON Pointer an invalid fixture must fail at.",
      fixtures,
    },
    null,
    2,
  ) + "\n",
);

// 3. py/remoteview_protocol/schema/*.schema.json
const pySchemaDir = resolve(shared, "py/remoteview_protocol/schema");
for (const file of schemaFiles)
  emit(resolve(pySchemaDir, file), readFileSync(resolve(schemaDir, file), "utf8"));
for (const stale of existsSync(pySchemaDir) ? readdirSync(pySchemaDir) : []) {
  if (stale.endsWith(".schema.json") && !schemaFiles.includes(stale)) {
    if (check) {
      drift = true;
      console.error(`drift: ${resolve(pySchemaDir, stale)} has no source in schema/ — delete it`);
    } else {
      rmSync(resolve(pySchemaDir, stale));
      console.log(`removed ${resolve(pySchemaDir, stale)}`);
    }
  }
}

// 4. ts/generated/messages.ts
const { bundle } = bundleSchemas(schemaDir);
const typescript = await compile(bundle, "AnyMessage", {
  additionalProperties: false, // no index signatures: unknown fields are tolerated at runtime (§14), not typed
  unreachableDefinitions: true,
  bannerComment: "",
  format: true,
});
emit(
  resolve(shared, "ts/generated/messages.ts"),
  [
    "// GENERATED by shared/scripts/generate.mjs from shared/schema/*.schema.json — do not edit.",
    "// Regenerate with `npm run generate -w shared`; CI fails on drift (ADR 0007 §2).",
    "",
    typescript,
  ].join("\n"),
);

// 5. py/remoteview_protocol/generated.py
const datamodelCodegen = resolve(shared, "py/.venv/bin/datamodel-codegen");
if (skipPython) {
  console.warn("skipping py/remoteview_protocol/generated.py (--skip-python)");
} else if (!existsSync(datamodelCodegen)) {
  console.error(
    `missing ${datamodelCodegen} — create the venv first (shared/README.md, "Python package")`,
  );
  process.exit(1);
} else {
  const work = mkdtempSync(resolve(tmpdir(), "remoteview-bundle-"));
  try {
    writeFileSync(resolve(work, "bundle.json"), JSON.stringify(bundle, null, 2));
    execFileSync(
      datamodelCodegen,
      [
        ...["--input", resolve(work, "bundle.json"), "--input-file-type", "jsonschema"],
        ...["--output", resolve(work, "generated.py"), "--output-model-type", "typing.TypedDict"],
        ...[
          "--target-python-version",
          "3.12",
          "--disable-timestamp",
          "--disable-future-imports",
          "--formatters",
          "builtin",
        ],
      ],
      { stdio: ["ignore", "inherit", "inherit"] },
    );
    const body = readFileSync(resolve(work, "generated.py"), "utf8").replace(/^(#.*\n)+\n?/, "");
    emit(
      resolve(shared, "py/remoteview_protocol/generated.py"),
      [
        "# GENERATED by shared/scripts/generate.mjs (datamodel-code-generator) from shared/schema/*.schema.json — do not edit.",
        "# Regenerate with `npm run generate -w shared`; CI fails on drift (ADR 0007 §2, §3).",
        '"""One `TypedDict` per protocol message (docs/protocol.md v1.0) and the `AnyMessage` union."""',
        "",
        body,
      ].join("\n"),
    );
  } finally {
    rmSync(work, { recursive: true, force: true });
  }
}

if (drift) process.exit(1);
