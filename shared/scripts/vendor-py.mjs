#!/usr/bin/env node
/**
 * Vendor the Python package into a consumer (ADR 0007 §3; docs/plan/protocol.md PRO-10):
 *
 *   node shared/scripts/vendor-py.mjs <target-dir>          # copy shared/py/remoteview_protocol → <target-dir>
 *   node shared/scripts/vendor-py.mjs <target-dir> --check  # exit 1 when <target-dir> differs from the source
 *
 * The Slicer extension calls it for `slicer-plugin/RemoteView/_vendor/remoteview_protocol` (SLC-03) and
 * imports from the vendored path only. The copy is the package directory (code + `schema/*.json`,
 * which `generate.mjs` keeps byte-identical to `shared/schema/`), minus caches, plus `VENDORED.json`:
 * `{ source, generatedBy, files: { <relative path>: <sha256> } }`, so a pure-Python fallback (no Node)
 * can produce and check the same manifest. `--check` compares every file's bytes in both directions:
 * a modified, missing or extra file is drift.
 */
import { createHash } from "node:crypto";
import { mkdirSync, readdirSync, readFileSync, rmSync, statSync, writeFileSync } from "node:fs";
import { dirname, join, relative, resolve, sep } from "node:path";
import { fileURLToPath } from "node:url";

const SOURCE = resolve(dirname(fileURLToPath(import.meta.url)), "../py/remoteview_protocol");
const MANIFEST = "VENDORED.json";
const SKIP_DIRS = new Set(["__pycache__", ".pytest_cache", ".ruff_cache", ".mypy_cache"]);
const SKIP_SUFFIXES = [".pyc", ".pyo"];

const args = process.argv.slice(2);
const check = args.includes("--check");
const target = args.find((a) => !a.startsWith("--"));
if (!target) {
  console.error("usage: vendor-py.mjs <target-dir> [--check]");
  process.exit(2);
}
const targetDir = resolve(target);

/** Relative POSIX paths of every file under `dir`, sorted. */
function listFiles(dir, base = dir) {
  const out = [];
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    if (entry.name.startsWith(".")) continue; // .DS_Store and other editor/OS droppings
    if (entry.isDirectory()) {
      if (!SKIP_DIRS.has(entry.name)) out.push(...listFiles(join(dir, entry.name), base));
    } else if (!SKIP_SUFFIXES.some((s) => entry.name.endsWith(s))) {
      out.push(relative(base, join(dir, entry.name)).split(sep).join("/"));
    }
  }
  return out.sort();
}

const sha256 = (buf) => createHash("sha256").update(buf).digest("hex");

const sourceFiles = listFiles(SOURCE);
const manifest = {
  $comment: `GENERATED by shared/scripts/vendor-py.mjs — vendored copy of shared/py/remoteview_protocol (ADR 0007 §3). Do not edit; re-run \`node shared/scripts/vendor-py.mjs <this dir>\`.`,
  source: "shared/py/remoteview_protocol",
  generatedBy: "shared/scripts/vendor-py.mjs",
  files: Object.fromEntries(sourceFiles.map((f) => [f, sha256(readFileSync(join(SOURCE, f)))])),
};
const manifestText = JSON.stringify(manifest, null, 2) + "\n";

if (check) {
  const drift = [];
  let targetFiles;
  try {
    targetFiles = listFiles(targetDir);
  } catch {
    console.error(`drift: ${targetDir} does not exist`);
    process.exit(1);
  }
  for (const f of sourceFiles) {
    const path = join(targetDir, f);
    let bytes;
    try {
      bytes = readFileSync(path);
    } catch {
      drift.push(`missing: ${f}`);
      continue;
    }
    if (!bytes.equals(readFileSync(join(SOURCE, f)))) drift.push(`modified: ${f}`);
  }
  for (const f of targetFiles) {
    if (f === MANIFEST) continue;
    if (!sourceFiles.includes(f)) drift.push(`extra: ${f}`);
  }
  let currentManifest = null;
  try {
    currentManifest = readFileSync(join(targetDir, MANIFEST), "utf8");
  } catch {
    drift.push(`missing: ${MANIFEST}`);
  }
  if (currentManifest !== null && currentManifest !== manifestText)
    drift.push(`modified: ${MANIFEST}`);
  if (drift.length > 0) {
    console.error(`vendored copy at ${targetDir} differs from ${SOURCE}:`);
    for (const line of drift) console.error(`  ${line}`);
    console.error(`run: node shared/scripts/vendor-py.mjs ${target}`);
    process.exit(1);
  }
  console.log(`vendored copy at ${targetDir} is up to date (${sourceFiles.length} files)`);
  process.exit(0);
}

// Copy: remove stale files first so the target mirrors the source exactly.
let existing;
try {
  existing = listFiles(targetDir);
} catch {
  existing = [];
}
for (const f of existing) {
  if (f !== MANIFEST && !sourceFiles.includes(f)) rmSync(join(targetDir, f));
}
for (const f of sourceFiles) {
  const dest = join(targetDir, f);
  mkdirSync(dirname(dest), { recursive: true });
  writeFileSync(dest, readFileSync(join(SOURCE, f)));
}
mkdirSync(targetDir, { recursive: true });
writeFileSync(join(targetDir, MANIFEST), manifestText);
// Drop now-empty directories left by removed files (one level is enough for this package layout).
for (const entry of readdirSync(targetDir, { withFileTypes: true })) {
  if (entry.isDirectory() && readdirSync(join(targetDir, entry.name)).length === 0)
    rmSync(join(targetDir, entry.name), { recursive: true });
}
const total = sourceFiles.length;
console.log(
  `vendored ${total} files (${statSync(join(targetDir, MANIFEST)).size} B manifest) into ${targetDir}`,
);
