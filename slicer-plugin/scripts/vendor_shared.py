#!/usr/bin/env python3
"""Vendor ``shared/py/remoteview_protocol`` into the Slicer module (ADR 0007 §3, SLC-03).

    python slicer-plugin/scripts/vendor_shared.py            # copy (refresh) the vendored package
    python slicer-plugin/scripts/vendor_shared.py --check    # exit 1 when the vendored copy drifted

The installed module must not import from ``shared/`` (it does not exist next to an installed extension), so the
package is copied to ``slicer-plugin/RemoteView/_vendor/remoteview_protocol`` together with ``VENDORED.json``
(``source``, ``files: {path: sha256}``). The canonical implementation is ``node shared/scripts/vendor-py.mjs``
(protocol workstream); this wrapper calls it when Node is available and otherwise runs a pure-Python port that
writes and checks the byte-identical manifest (``--python`` forces the port). Development tool only — never
imported by the module.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import shutil
import subprocess
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[2]
SOURCE = REPO_ROOT / "shared" / "py" / "remoteview_protocol"
NODE_SCRIPT = REPO_ROOT / "shared" / "scripts" / "vendor-py.mjs"
DEFAULT_TARGET = REPO_ROOT / "slicer-plugin" / "RemoteView" / "_vendor" / "remoteview_protocol"
MANIFEST = "VENDORED.json"
# Mirrors SKIP_DIRS / SKIP_SUFFIXES / dot-file rule of vendor-py.mjs.
SKIP_DIRS = {"__pycache__", ".pytest_cache", ".ruff_cache", ".mypy_cache"}
SKIP_SUFFIXES = (".pyc", ".pyo")
MANIFEST_COMMENT = (
    "GENERATED by shared/scripts/vendor-py.mjs — vendored copy of shared/py/remoteview_protocol "
    "(ADR 0007 §3). Do not edit; re-run `node shared/scripts/vendor-py.mjs <this dir>`."
)


def list_files(directory: Path) -> list[str]:
    """Relative POSIX paths of every vendorable file under ``directory``, sorted (same rules as the Node tool)."""
    out: list[str] = []
    for entry in sorted(directory.iterdir()):
        if entry.name.startswith("."):
            continue
        # like Node's Dirent.isDirectory(): never follow links
        if entry.is_dir() and not entry.is_symlink():
            if entry.name not in SKIP_DIRS:
                out += [f"{entry.name}/{sub}" for sub in list_files(entry)]
        elif not entry.name.endswith(SKIP_SUFFIXES):
            out.append(entry.name)
    return sorted(out)


def manifest_text(source: Path = SOURCE) -> str:
    files = {f: hashlib.sha256((source / f).read_bytes()).hexdigest() for f in list_files(source)}
    manifest = {
        "$comment": MANIFEST_COMMENT,
        "source": "shared/py/remoteview_protocol",
        "generatedBy": "shared/scripts/vendor-py.mjs",
        "files": files,
    }
    # JSON.stringify(manifest, null, 2) + "\n"
    return json.dumps(manifest, indent=2, ensure_ascii=False) + "\n"


def drift(target: Path, source: Path = SOURCE) -> list[str]:
    """Differences between ``target`` and ``source`` (modified, missing and extra files, stale manifest)."""
    if not target.is_dir():
        return [f"missing: {target}"]
    problems: list[str] = []
    source_files = list_files(source)
    target_files = list_files(target)
    for f in source_files:
        # a link could point anywhere; the copy holds regular files only
        if (target / f).is_symlink():
            problems.append(f"symlink: {f}")
        elif not (target / f).is_file():
            problems.append(f"missing: {f}")
        elif (target / f).read_bytes() != (source / f).read_bytes():
            problems.append(f"modified: {f}")
    problems += [f"extra: {f}" for f in target_files if f != MANIFEST and f not in source_files]
    manifest = target / MANIFEST
    # compared as bytes: no newline translation
    expected = manifest_text(source).encode("utf-8")
    if not manifest.is_file():
        problems.append(f"missing: {MANIFEST}")
    elif manifest.is_symlink() or manifest.read_bytes() != expected:
        problems.append(f"modified: {MANIFEST}")
    return problems


def refuse_foreign_target(target: Path) -> None:
    """Copy mode deletes files that are not in the source, with either tool: only ever mirror into a (new or
    previously vendored) ``remoteview_protocol`` directory."""
    if target.name != "remoteview_protocol" or (
        target.is_dir() and any(target.iterdir()) and not (target / MANIFEST).is_file()
    ):
        raise SystemExit(
            f"refusing to vendor into {target}: not an (empty or vendored) remoteview_protocol directory"
        )


def copy(target: Path, source: Path = SOURCE) -> int:
    """Mirror ``source`` into ``target`` (call :func:`refuse_foreign_target` first, as :func:`main` does)."""
    source_files = list_files(source)
    if target.is_dir():
        for f in list_files(target):
            if f != MANIFEST and f not in source_files:
                (target / f).unlink()
    for f in source_files:
        (target / f).parent.mkdir(parents=True, exist_ok=True)
        if (target / f).is_symlink():  # never write through a link
            (target / f).unlink()
        shutil.copyfile(source / f, target / f)
    target.mkdir(parents=True, exist_ok=True)
    if (target / MANIFEST).is_symlink():
        (target / MANIFEST).unlink()
    (target / MANIFEST).write_text(manifest_text(source), encoding="utf-8", newline="\n")
    for entry in target.iterdir():
        if entry.is_dir() and not entry.is_symlink() and not any(entry.iterdir()):
            entry.rmdir()
    return len(source_files)


def find_node() -> str | None:
    """Absolute path of a Node 22 executable able to run the canonical tool, or ``None``."""
    node = shutil.which("node")
    if node is None or not NODE_SCRIPT.is_file():
        return None
    try:
        version = subprocess.run(
            [node, "--version"], capture_output=True, text=True, check=True, timeout=30
        )
    except (OSError, subprocess.SubprocessError):
        return None
    return node if version.stdout.strip().startswith("v22.") else None


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument(
        "--check", action="store_true", help="exit 1 when the vendored copy drifted"
    )
    parser.add_argument(
        "--python", action="store_true", help="use the pure-Python port even if Node 22 exists"
    )
    parser.add_argument("--target", type=Path, default=DEFAULT_TARGET, help=argparse.SUPPRESS)
    args = parser.parse_args(argv)

    # Guards for both tools (vendor-py.mjs has neither): never mirror into an unrelated directory, never write or
    # read through symlinks inside the copy.
    target = args.target
    links = [f for f in list_files(target) if (target / f).is_symlink()] if target.is_dir() else []
    if args.check and links:
        print(f"vendored copy at {target} contains symlinks: {links}", file=sys.stderr)
        return 1
    if not args.check:
        refuse_foreign_target(target)
        for f in links:
            (target / f).unlink()
    node = None if args.python else find_node()
    if node is not None:
        cmd = [node, str(NODE_SCRIPT), str(args.target), *(["--check"] if args.check else [])]
        return subprocess.run(cmd, check=False).returncode

    if args.check:
        problems = drift(args.target)
        if problems:
            print(f"vendored copy at {args.target} differs from {SOURCE}:", file=sys.stderr)
            for line in problems:
                print(f"  {line}", file=sys.stderr)
            print("run: python slicer-plugin/scripts/vendor_shared.py", file=sys.stderr)
            return 1
        print(f"vendored copy at {args.target} is up to date ({len(list_files(SOURCE))} files)")
        return 0
    count = copy(args.target)
    print(f"vendored {count} files into {args.target}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
