// QA-03 helpers for tests/e2e/join.spec.ts (and the QA-07 log/HAR suite that re-runs its scenarios): a network
// recorder over every request and WebSocket of a browser context, the node list of a fixture GLB, and an in-page
// probe that timestamps the Join click, the model becoming loaded and the frame drawn after it.
//
// Secrets (NFR-12): the recorder keeps URLs, headers and frames in memory only; specs reduce them to booleans and
// counts before asserting, and wrap browser calls that take a secret in `redacted()`, so no failure message can
// carry a code or a token. (A retained trace still shows the typed code: artefacts are internal, tests/README.md.)

import { readFileSync } from "node:fs";
import path from "node:path";
import type { BrowserContext, Page, Request, WebSocket } from "@playwright/test";
import { FIXTURE_MANIFEST, FIXTURES_DIR } from "../../harness/paths.ts";

export interface FixtureNode {
  readonly nodeId: string;
  readonly name: string;
}

/** `nodeIds` of a fixture as `manifest.json` lists them (generated by PRO-08). */
export function manifestNodeIds(fixture: string): string[] {
  const manifest = JSON.parse(readFileSync(FIXTURE_MANIFEST, "utf8")) as {
    files: Record<string, { nodeIds: string[] }>;
  };
  const entry = manifest.files[fixture];
  if (!entry) throw new Error(`${fixture} is not in manifest.json`);
  return entry.nodeIds;
}

/**
 * The manifest entries (`T.extras`, protocol §7.3) of a fixture GLB in node order: the display names are not in
 * `manifest.json`, only in the GLB's JSON chunk (GLB 2.0 header: magic, version, length; then chunk 0 = JSON with
 * its byte length at offset 12 and the JSON from offset 20 — glTF 2.0 spec §4.4).
 */
export function fixtureNodes(fixture: string): FixtureNode[] {
  const glb = readFileSync(path.join(FIXTURES_DIR, fixture));
  const jsonLength = glb.readUInt32LE(12);
  const gltf = JSON.parse(glb.subarray(20, 20 + jsonLength).toString("utf8")) as {
    nodes: { extras?: { nodeId?: string; kind?: string; name?: string } }[];
  };
  return gltf.nodes
    .map((n) => n.extras)
    .filter((e): e is { nodeId: string; kind: string; name: string } => !!e?.nodeId && e.kind !== "root")
    .map((e) => ({ nodeId: e.nodeId, name: e.name }));
}

export interface SocketRecord {
  readonly url: string;
  /** Text frames from the relay, parsed (malformed ones are skipped). In memory only: they hold tokens. */
  readonly messages: Record<string, unknown>[];
  /** Binary frames from the relay (snapshot chunks, §6.3). */
  binaryFrames: number;
}

export interface NetworkRecord {
  readonly requests: Request[];
  readonly sockets: SocketRecord[];
}

/**
 * Records every request of `context` (`browserContext.on('request')` also sees service workers and every page of
 * the context — playwright-core types.d.ts, BrowserContext "request") and every WebSocket of the given pages
 * (`page.on('websocket')`; a WebSocket upgrade is not reported as a `request`). Call before the first navigation.
 */
export function recordNetwork(context: BrowserContext, pages: Page[]): NetworkRecord {
  const record: NetworkRecord = { requests: [], sockets: [] };
  context.on("request", (request) => record.requests.push(request));
  for (const page of pages) watchSockets(page, record);
  return record;
}

/** Adds the WebSockets of `page` to `record` (a page opened after `recordNetwork`). */
export function watchSockets(page: Page, record: NetworkRecord): void {
  page.on("websocket", (ws: WebSocket) => {
    const socket: SocketRecord = { url: ws.url(), messages: [], binaryFrames: 0 };
    record.sockets.push(socket);
    // `framereceived` payload is `string | Buffer` (playwright-core types.d.ts, WebSocket "framereceived").
    ws.on("framereceived", ({ payload }) => {
      if (typeof payload !== "string") {
        socket.binaryFrames++;
        return;
      }
      try {
        socket.messages.push(JSON.parse(payload) as Record<string, unknown>);
      } catch {
        // not JSON: not a protocol message
      }
    });
  });
}

/**
 * `text` without the stack's own origin (`http://127.0.0.1:<port>`, `ws://…`, `127.0.0.1:<port>`): a code can be
 * all digits (`23456`, §4.2 alphabet) and would then match the harness's random port by chance, not by a leak.
 */
function withoutOrigin(text: string, origin: string): string {
  const host = new URL(origin).host;
  return text.split(host).join("");
}

/**
 * Whether `code` appears in any request or WebSocket URL, in either case (the viewer uppercases input, §5.1). A
 * boolean, so a failing assertion prints no code. Whole URLs are checked (minus the stack's host:port); the
 * deep-link navigation `/j#CODE` passes because both engines report a request URL without its fragment (never
 * sent, RFC 3986 §3.5) — measured on Playwright 1.60 WebKit and Chromium.
 */
export function codeInAnyUrl(record: NetworkRecord, code: string, origin: string): boolean {
  const lower = code.toLowerCase();
  const urls = [...record.requests.map((r) => r.url()), ...record.sockets.map((s) => s.url)];
  return urls.map((url) => withoutOrigin(url, origin)).some((url) => url.includes(code) || url.includes(lower));
}

/**
 * Whether `code` appears in any request header value of the run (e.g. a `Referer` carrying `/j#CODE`), in either
 * case. A boolean, like `codeInAnyUrl`. Call while the record's pages are open: `allHeaders()` asks the browser
 * for the raw headers (playwright-core types.d.ts, Request.allHeaders).
 */
export async function codeInAnyHeader(record: NetworkRecord, code: string, origin: string): Promise<boolean> {
  const lower = code.toLowerCase();
  const values = (await Promise.all(record.requests.map((r) => r.allHeaders()))).flatMap(Object.values);
  return values.map((v) => withoutOrigin(v, origin)).some((value) => value.includes(code) || value.includes(lower));
}

/**
 * Runs a browser action whose arguments hold a secret (`page.goto("/j#CODE")`, `keyboard.type(code)`) and, if it
 * fails, rethrows an error with every secret replaced by `<redacted>`: Playwright's message and call log repeat
 * the URL or text (e.g. `navigating to "…/j#CODE"`), and the reporter prints both into the CI log (NFR-12). The
 * original error is not attached as `cause`, since reporters print that too.
 */
export async function redacted<T>(secrets: readonly string[], action: () => Promise<T>): Promise<T> {
  try {
    return await action();
  } catch (error) {
    const scrub = (text: string) =>
      secrets
        .flatMap((s) => [s, s.toLowerCase()])
        .filter((s) => s.length > 0)
        .reduce((t, s) => t.split(s).join("<redacted>"), text);
    const original = error instanceof Error ? error : new Error(String(error));
    const clean = new Error(scrub(original.message));
    clean.stack = scrub(original.stack ?? clean.message);
    throw clean;
  }
}

/** `GET /api/scene/:sceneVersion` requests (protocol §10). */
export const sceneRequests = (record: NetworkRecord): Request[] =>
  record.requests.filter((r) => /^\/api\/scene\/\d+$/.test(new URL(r.url()).pathname));

/** The `viewer.joined` messages the relay sent on the recorded sockets (hold the viewer token: memory only). */
export const joinedMessages = (record: NetworkRecord): Record<string, unknown>[] =>
  record.sockets.flatMap((s) => s.messages.filter((m) => m["type"] === "viewer.joined"));

export interface JoinTimes {
  /** `performance.now()` of the Join click, -1 before it. */
  readonly click: number;
  /** When `.viewer` got `data-model="loaded"` (render/viewer.ts `setModel`). */
  readonly loaded: number;
  /** Two animation frames after `loaded`: the viewer renders on demand in the frame after `setModel`. */
  readonly frame: number;
  /** `history.length` when the document started, before the viewer's script ran. */
  readonly historyAtStart: number;
}

/**
 * Installs the in-page probe (`page.addInitScript` runs after the document is created and before any of its
 * scripts — playwright-core types.d.ts, Page.addInitScript), so it sees the deep link before the viewer takes it.
 */
export async function installJoinProbe(page: Page): Promise<void> {
  await page.addInitScript(() => {
    const times = { click: -1, loaded: -1, frame: -1, historyAtStart: history.length };
    (window as unknown as { __qa03: typeof times }).__qa03 = times;
    document.addEventListener(
      "click",
      (event) => {
        const target = event.target as Element | null;
        if (times.click < 0 && target?.closest?.(".code-entry__join")) times.click = performance.now();
      },
      true,
    );
    new MutationObserver(() => {
      if (times.loaded >= 0 || !document.querySelector(".viewer[data-model='loaded']")) return;
      times.loaded = performance.now();
      requestAnimationFrame(() => requestAnimationFrame(() => (times.frame = performance.now())));
    }).observe(document, { subtree: true, childList: true, attributes: true, attributeFilter: ["data-model"] });
  });
}

export const joinTimes = (page: Page): Promise<JoinTimes> =>
  page.evaluate(() => (window as unknown as { __qa03: JoinTimes }).__qa03);
